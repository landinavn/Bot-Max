async def seed(owner):
    async with repo.connect() as db:
        prior = await repo.one(db, 'SELECT id FROM cartoon_projects WHERE seed_key=?', ('anya-s1-v1',))
    project = prior['id'] if prior else await repo.create('project', WORLD, owner_id=owner, title='Маленькие чудеса Ани', season=1, seed_key='anya-s1-v1')
    existing = {c['name']:c['id'] for c in await repo.children('character',project)}
    cast = {}
    for name,spec in CHARACTERS:
        cast[name] = existing.get(name) or await repo.create('character',spec,project_id=project,name=name)
    episodes = await repo.children('episode',project)
    episode = episodes[0]['id'] if episodes else await repo.create('episode', dict(approved=True, target_seconds=40, max_target_seconds=45,
        ending=['Маленькие чудеса Ани', 'А о чём мечтаете вы?', 'Продолжение следует…'],
        source='Утверждённый владельцем сценарий в переписке; естественные голоса, допустимо 42–45 секунд.'),
        project_id=project, title='Опять Новый год?!', number=1)
    existing_scenes = {s['number'] for s in await repo.children('scene',episode)}
    for number, (title, duration, people, visual, dialogue, camera, sound) in enumerate(SCENES, 1):
        if number in existing_scenes:
            continue
        await repo.create('scene', dict(title=title, duration=duration, approved=True,
            characters=[cast[name] for name in people], visual=visual, camera=camera, sound=sound,
            dialogue=[dict(character_id=cast[name], text=text, direction=direction) for name,text,direction in dialogue]),
            episode_id=episode, number=number)
    return project
