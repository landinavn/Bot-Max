def build_request(details, label, audio_format, style=None):
    from audio_service import build_song_request
    from mothers_day import MOTHER_LABELS
    if label in MOTHER_LABELS:
        return build_song_request(details, label, audio_format, style)
    _, tags, _ = build_song_request('Личные сведения', label, audio_format, style)
    title = f"{label}: {details.split(',')[0]}"[:80]
    if not details.strip() or len(details) > 1000:
        raise ValueError('Расскажите о герое песни в пределах 1000 символов.')
    brief = {'version': 1, 'details': details.strip(), 'occasion': label, 'format': audio_format}
    tags += ', vocals from the start, no instrumental intro'
    return PREFIX + json.dumps(brief, ensure_ascii=False), tags, title


def parse_request(notes):
    if not notes.startswith(PREFIX):
        return None
    try:
        brief = json.loads(notes[len(PREFIX):])
        if (not isinstance(brief, dict) or brief.get('version') != 1
                or brief.get('format') not in ('fun', 'gift')
                or any(not isinstance(brief.get(k), str) or not brief[k].strip() for k in ('details', 'occasion'))
                or len(brief['details']) > 1000):
            raise ValueError
        return brief
    except (ValueError, TypeError):
        raise ValueError('Некорректные данные персональной песни.') from None


def validate_lyrics(text, audio_format):
    sections = re.findall(r'\[([^\]]+)\]', text)
    expected = ['Verse 1', 'Chorus'] if audio_format == 'fun' else ['Verse 1', 'Chorus', 'Verse 2', 'Chorus', 'Bridge', 'Chorus']
    if sections != expected or not text.startswith('[Verse 1]') or len(text)>5000 or '```' in text:
        raise ValueError('Не соблюдена структура персональной песни.')
    bodies = re.split(r'\[[^\]]+\]', text)[1:]
    limits = [(2,4),(4,4)] if audio_format == 'fun' else [(6,8),(6,6),(6,8),(6,6),(4,4),(6,6)]
    for body,(minimum,maximum) in zip(bodies,limits):
        lines = [line.strip() for line in body.splitlines() if line.strip()]
        if not minimum <= len(lines) <= maximum or '+' in lines:
            raise ValueError('Проверьте объём куплетов и припева песни.')
    choruses = [body.strip() for tag,body in zip(sections,bodies) if tag=='Chorus']
    if len(set(choruses)) != 1:
        raise ValueError('Припевы персональной песни должны совпадать.')
    return text
